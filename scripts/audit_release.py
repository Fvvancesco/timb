"""Read-only checks of frozen experiment artifacts; no simulation or model fitting."""
from collections import Counter
import json
from pathlib import Path
import sys
import joblib

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'src'))
from icon_pokemon.adapter import sha256, save_json


def verify_hashes(hashes):
    for path, digest in hashes.items():
        if sha256(ROOT / path) != digest:
            raise ValueError(f'Changed artifact: {path}')


def read_jobs(path, jobs):
    rows = [json.loads(line) for line in path.read_text().splitlines()]
    expected = {job['job_id']: job for job in jobs}
    identifiers = [row['job_id'] for row in rows]
    if len(identifiers) != len(set(identifiers)) or set(identifiers) != set(expected):
        raise ValueError(f'Incomplete/duplicated labels: {path}')
    for row in rows:
        if any(row.get(key) != value for key, value in expected[row['job_id']].items()):
            raise ValueError(f'Job metadata changed: {row["job_id"]}')
        if row['outcome'] in ('team_a', 'team_b', 'draw') and not row['replay_verified']:
            raise ValueError('Unverified outcome')
    return rows


def main():
    catalog = json.loads((ROOT / 'data/processed/dataset_v1/catalog.json').read_text())
    teams = catalog['teams']
    compositions = [tuple(sorted(t['species_composition'])) for t in teams.values()]
    if len(compositions) != len(set(compositions)):
        raise ValueError('Repeated base-species compositions in catalog')
    dev, all_ids = [], set()
    for dataset in ('v2', 'v3', 'v4'):
        manifest = json.loads((ROOT / f'config/dataset_{dataset}_manifest.json').read_text())
        jobs = [j for j in manifest['jobs'] if j['split'] in ('train', 'validation')]
        rows = read_jobs(ROOT / f'data/processed/dataset_{dataset}/development_labels.jsonl', jobs)
        if all_ids & {r['job_id'] for r in rows}:
            raise ValueError('Duplicated development IDs across versions')
        all_ids.update(r['job_id'] for r in rows)
        if any(teams[r[k]]['split'] == 'test' for r in rows for k in ('team_a_id', 'team_b_id')):
            raise ValueError('Held-out team in development')
        dev.extend(rows)
    folder = ROOT / 'data/processed/final_v1'
    manifest = json.loads((folder / 'manifest.json').read_text())
    marker = json.loads((folder / 'evaluation_started.json').read_text())
    if marker['manifest_sha256'] != sha256(folder / 'manifest.json'):
        raise ValueError('Final manifest changed after execution start')
    verify_hashes({**manifest['hashes'], **manifest['code_hashes']})
    model_path = ROOT / manifest['model_path']
    if sha256(model_path) != manifest['model_sha256'] or marker['model_sha256'] != manifest['model_sha256']:
        raise ValueError('Final model changed')
    model = joblib.load(model_path)  # Trusted artifact generated by this project.
    verify_hashes(model['code_hashes'])
    verify_hashes(model['input_hashes'])
    final = read_jobs(folder / 'labels.jsonl', manifest['jobs'])
    predictions = json.loads((folder / 'predictions.json').read_text())
    probability = {r['job_id']: r['p_team_a'] for r in predictions}
    prediction_jobs = [r for r in final if r['split'] == 'test']
    if len(probability) != len(predictions) or set(probability) != {r['job_id'] for r in prediction_jobs}:
        raise ValueError('Prediction job IDs differ')
    pairs = {}
    for row in prediction_jobs:
        if any(teams[row[k]]['split'] != 'test' for k in ('team_a_id', 'team_b_id')):
            raise ValueError('Non-held-out team in predictive final')
        p = probability[row['job_id']]
        if not 0 <= p <= 1:
            raise ValueError('Invalid probability')
        pairs.setdefault((row['pair_id'], row['root_seed']), []).append(p)
    if any(len(p) != 2 or abs(sum(p) - 1) > 1e-12 for p in pairs.values()):
        raise ValueError('Predictions are not complementary under side swap')
    requests = json.loads((folder / 'requests.json').read_text())
    allowed = {i for t in teams.values() if t['split'] == 'train' for i in t['set_ids']}
    for request in requests:
        if teams[request['opponent_id']]['split'] != 'test':
            raise ValueError('Selector opponent not held out')
        if any(not set(t['selected_ids']) <= allowed for t in request['pool']['teams']):
            raise ValueError('Candidate outside training catalog')
        candidates = {tuple(sorted(t['selected_ids'])) for t in request['pool']['teams']}
        if any(tuple(sorted(choice['ids'])) not in candidates for choice in request['selection']['choices'].values()):
            raise ValueError('Selector chose outside common pool')
    report = json.loads((ROOT / 'reports/final_evaluation.json').read_text())
    verify_hashes(report['hashes'])
    result = {'status': 'ok', 'catalog_teams': len(teams), 'catalog_sets': len(catalog['sets']),
              'team_splits': dict(Counter(t['split'] for t in teams.values())),
              'development_records': len(dev), 'development_outcomes': dict(Counter(str(r['outcome']) for r in dev)),
              'final_records': len(final), 'final_statuses': dict(Counter(r['status'] for r in final)),
              'prediction_pairs_with_complementary_probabilities': len(pairs),
              'requests': len(requests), 'model_selection': manifest['model_selection'],
              'scope': 'Hashes, manifest metadata, splits, prediction symmetry and candidate membership; raw replay verification is recorded by collectors, not rerun here.',
              'script_sha256': sha256(Path(__file__))}
    save_json(ROOT / 'reports/release_audit.json', result)
    print(json.dumps(result, indent=2))


if __name__ == '__main__':
    main()
